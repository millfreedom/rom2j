    private static final Map<Integer, SfxSounds> BY_ID = createIdLookup();

    public final int id;

    /**
     * Java enum constructor for `SoundManager.SFX_SOUNDS` entries extracted from `sfx.reg`.
     * not ported.
     */
    SfxSounds(int id) {
        this.id = id;
    }

    /**
     * Java lookup helper for hardcoded SFX ids.
     * not ported.
     */
    public static SfxSounds fromId(int id) {
        SfxSounds sound = BY_ID.get(id);
        return sound == null ? UNKNOWN : sound;
    }

    /**
     * Java helper for populating the id lookup table.
     * not ported.
     */
    private static Map<Integer, SfxSounds> createIdLookup() {
        Map<Integer, SfxSounds> lookup = new HashMap<>();
        for (SfxSounds sound : values()) {
            if (sound.id >= 0) {
                lookup.put(sound.id, sound);
            }
        }
        return lookup;
    }
